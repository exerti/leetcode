/**
 * 用队列实现栈 (LeetCode 225)
 *
 * 和"栈实现队列"正好相反：
 *   栈实现队列 → 两个栈，倒一次反转 LIFO 变 FIFO
 *   队列实现栈 → 每次 push 后把前面的元素重新入队，让新元素排到队头
 *
 * 队列特性：先进先出 → 1,2,3 进去，1,2,3 出来
 * 栈特性：  后进先出 → 1,2,3 进去，3,2,1 出来
 *
 * trick：每次 push 后，把新元素之前的所有元素依次 poll 再 offer，
 *        让新元素"插队"到最前面
 *
 * 手写推演（两个队列法）：
 *   操作      q1           q2          说明
 *   ─────────────────────────────────────────────
 *   push 1    [1]          []          直接入 q1
 *   push 2    []           [2,1]       push 2 到空 q2，把 q1 全部倒入 q2，交换引用
 *   push 3    [3,2,1]      []          push 3 到空 q1，把 q2 全部倒入 q1，交换
 *   pop()     [2,1]        []          q1.removeFirst() → 3
 *   pop()     [1]          []          q1.removeFirst() → 2
 *
 * 手写推演（单队列法 — 更简洁）：
 *   操作      q            说明
 *   ──────────────────────────────────────
 *   push 1    [1]          正常入队
 *   push 2    [2,1]        offer(2) 后，把前面的 1 poll 再 offer → 2 变队头
 *   push 3    [3,2,1]      offer(3) 后，把 2,1 依次 poll 再 offer
 *   pop()     [2,1]        poll → 3
 *   pop()     [1]          poll → 2
 *   pop()     []           poll → 1
 */

class MyStack {

    private val q = ArrayDeque<Int>()

    fun push(x: Int) {
        val size = q.size
        q.addLast(x)                     // 先正常入队尾
        repeat(size) {                   // 把前面 size 个元素逐个移到队尾
            q.addLast(q.removeFirst())   // 新元素自然被推到队头
        }
    }

    fun pop(): Int = q.removeFirst()

    fun top(): Int = q.first()

    fun empty(): Boolean = q.isEmpty()

}

